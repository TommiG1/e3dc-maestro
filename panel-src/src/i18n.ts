export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export interface I18n {
  t: Translate;
  phase: (id: string) => string;
}

export function makeI18n(language: string): I18n {
  const isDe = !language || language.toLowerCase().startsWith("de");
  const dict: Record<Key, string> = isDe ? de : en;
  const phases = isDe ? PHASES_DE : PHASES_EN;
  return {
    t: (key, vars) => {
      let s = dict[key];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    phase: (id) => phases[id] ?? id,
  };
}
